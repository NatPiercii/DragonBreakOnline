// runs, one zone per placement so they stand where the Creation Kit put them; Alduinak's
// NpcSpawnSystem places them on claim, before the party is moved in. Loot in every container is
// generated by the server from loot.json per difficulty (big chests get the real roll, urns and
// sacks a little), some big chests are locked for the Lockpicking skill, and every lootable
// container glows until opened. Humanoid bodies are looted with E for a small roll; other spawned
// corpses are trimmed on death so a body yields loot, not a full kit. When the lease ends
// everyone inside is put back at the entrance and each member waits an hour before claiming that
// dungeon again.
//
// gamemode-config.json "dungeons": { enabled, leaseMinutes, cooldownMinutes, warnMinutes,
//   graceMinutes, partyMax, lockedShare: {story, normal, hard, nightmare} }
