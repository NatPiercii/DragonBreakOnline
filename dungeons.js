// DragonBreak Online: dungeons as leases. Loaded by gamemode.js (re-required on every hot reload).
//
// One world, so a dungeon cannot be cloned per party. Instead the first party to use an entrance
// claims the dungeon: the leader picks a difficulty, the party is moved inside, everyone else is
// refused at the door until the hour ends, the party leaves, or the dungeon is cleared (every
// enemy dead, every chest opened). Enemies are Bethesda's placements (dungeons.json, each leveled
